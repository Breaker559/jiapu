        page.get_by_role('button',name='我已保存',exact=True).click()
        expect(page.locator('.family-switch strong')).to_have_text('林家的记忆')
        me=context.request.get(BASE+'/api/me').json();newfid=me['families'][0]['id']
        assert me['user']['admin'] is False and len(me['families'])==1
        assert context.request.get(f'{BASE}/api/families/{owner_fid}/state').status==404
        assert context.request.get(f'{BASE}/api/families/{newfid}/state').json()['records']==[]
        context.request.post(f'{BASE}/api/families/{newfid}/records/person',data={'data':{'name':'林家独有人物'}},headers={'X-CSRF-Token':me['csrf']})
        # Opening the avatar must not mutate the session; account actions are explicit.
        trigger=page.get_by_role('button',name='账号菜单',exact=True)
        trigger.click()
        menu=page.get_by_role('menu',name='账号操作')
