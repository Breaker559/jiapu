ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'test-results';DATA=OUT/('accounts-'+str(time.time_ns()));DATA.mkdir(parents=True)
env={**os.environ,'QINPU_DATA':str(DATA),'PYTHONUTF8':'1','QINPU_ALLOW_REGISTRATION':'1'}
env.pop('DATABASE_URL',None)
log=(DATA/'server.log').open('w',encoding='utf-8')
BASE='http://127.0.0.1:8882'
def start():
    process=subprocess.Popen([str(ROOT/'.venv/Scripts/python.exe'),'-m','uvicorn','server.app:app','--host','127.0.0.1','--port','8882'],cwd=ROOT,env=env,stdout=log,stderr=log,creationflags=subprocess.CREATE_NO_WINDOW)
    for _ in range(50):
        try:urllib.request.urlopen(BASE+'/api/health',timeout=1);return process
        except Exception:time.sleep(.2)
    process.terminate();process.wait(timeout=15)
    raise RuntimeError('Isolated test server failed to start')
server=start()
